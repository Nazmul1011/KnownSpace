// Collects the lucide icon names used by the content and writes a tree-shakeable map.
//   node scripts/gen-icons.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
const names = new Set();
for (const dir of ['src/domain/knowledge/data/text', 'src/domain/knowledge/data/more']) {
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.ts')) continue;
    const src = readFileSync(`${dir}/${f}`, 'utf8');
    for (const m of src.matchAll(/icon: '([a-z0-9-]+)'/g)) names.add(m[1]);
  }
}
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const sorted = [...names].sort();
const missing = sorted.filter((n) => !existsSync(`node_modules/lucide-react/dist/esm/icons/${n}.mjs`));
if (missing.length) console.warn('missing icons:', missing);
const ok = sorted.filter((n) => !missing.includes(n));
const out = `// generated by scripts/gen-icons.mjs — do not edit\nimport { ${ok.map(pascal).join(', ')} } from 'lucide-react';\nimport type { LucideIcon } from 'lucide-react';\n\nexport const icons: Record<string, LucideIcon> = {\n${ok.map((n) => `  '${n}': ${pascal(n)},`).join('\n')}\n};\n`;
writeFileSync('src/shared/ui/icons.generated.ts', out);
console.log(ok.length, 'icons');
